"""Collect every number of the P6 paper that is not in an experiment summary, from its source file.

  python scripts/p6_paper_facts.py   -> results/p6_paper_facts/facts.md
Sources: results/p6_e0/tiles.csv, results/p6_e0/harmonisation_regression_check.csv, the E1 target tables, the build
reports of domain S and R, the E1-R target summary, the gain table of domain R and the multi-scale gain table
(copied from the GPU server into results/p6_paper_facts/).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import ndimage  # noqa: F401  (kept for parity with the analysis environment)

ROOT = Path(__file__).resolve().parents[1]
F = ROOT / "results/p6_paper_facts"
TARGET = ["B05", "B06", "B07", "B8A", "B11", "B12"]


def main():
    md = ["# Facts used in the P6 manuscript (generated by scripts/p6_paper_facts.py)", ""]
    t = pd.read_csv(ROOT / "results/p6_e0/tiles.csv")
    md += ["## SEN2NEON tiles (results/p6_e0/tiles.csv)", "",
           f"- tiles {len(t)}, sites {t.site.nunique()}, years {t.year.min()}-{t.year.max()}",
           f"- |dt| days: median {t.dt_days.abs().median():.0f}, max {t.dt_days.abs().max():.0f}",
           f"- status counts: {t.status.value_counts().to_dict()}"]
    ok = t[(t.status == "ok") & (t.g_peak >= 0.1)]
    md += [f"- reliable (status ok and guide phase-correlation peak >= 0.1): {len(ok)}; removed for low peak: "
           f"{(t.status == 'ok').sum() - len(ok)}",
           f"- tiles with |tile shift| > 0.5 px: guide {(ok.g_mag > 0.5).mean():.3f}, target {(ok.t_mag > 0.5).mean():.3f}"]
    bins = pd.cut(ok.dt_days.abs(), [-0.5, 3, 7, 15, 40])
    md += [f"- tiles per |dt| bin (0-3, 4-7, 8-15, 16-40 d): {bins.value_counts(sort=False).tolist()}", ""]

    md += ["## Registration accuracy on domain S with known shifts (data/p6_e1/targets_*.csv)", ""]
    for s in ("S1_shift", "S2_realistic", "S3_stress"):
        p = F / f"e1_targets_{s}.csv"
        if not p.exists():
            continue
        d = pd.read_csv(p)
        e = np.hypot(d.est_dy - d.dy, d.est_dx - d.dx)
        md.append(f"- {s}: n {len(d)}, error median {e.median():.3f} px, rms {np.sqrt((e ** 2).mean()):.3f} px, "
                  f"bias dy {(d.est_dy - d.dy).mean():+.4f}, dx {(d.est_dx - d.dx).mean():+.4f}, "
                  f"median |true shift| {np.hypot(d.dy, d.dx).median():.2f} px")
    md.append("")

    s = json.loads((F / "domain_s_build_report.json").read_text())
    md += ["## Domain S (data/p6_domain_s/build_report.json)", "",
           f"- train {s['train']['n_tiles']} tiles / {s['train']['n_sites']} sites; val {s['val']['n_tiles']} tiles / "
           f"{s['val']['n_sites']} sites", ""]
    r = json.loads((F / "domain_r_build_report.json").read_text())
    md += ["## Domain R (data/p6_domain_r/build_report.json)", ""]
    md += [f"- {k}: {v['n_tiles']} tiles / {v['n_sites']} sites" for k, v in r.items()
           if isinstance(v, dict) and "n_tiles" in v]
    g = pd.read_csv(F / "domain_r_gains.csv").drop_duplicates(["tile", "band"])
    q = g.groupby("band").a_hat.quantile([0.25, 0.5, 0.75]).unstack()
    md += [f"- gain a_hat over {g.tile.nunique()} unique tiles, median [IQR]: " +
           ", ".join(f"{b} {q.loc[b, 0.5]:.3f} [{q.loc[b, 0.25]:.3f}, {q.loc[b, 0.75]:.3f}]" for b in TARGET), ""]
    e = json.loads((F / "e1r_targets_summary.json").read_text())
    md += ["## E1-R emulated harmonisation (data/p6_e1r/summary.json; medians over tiles)", "",
           "- m: " + ", ".join(f"{b} {e['m'][b]:.3f}" for b in TARGET),
           "- a_hat (estimate of m by Eq. 3): " + ", ".join(f"{b} {e['a_hat'][b]:.3f}" for b in TARGET),
           "- R: " + ", ".join(f"{b} {e['R'][b]:.3f}" for b in TARGET), ""]
    am = pd.read_csv(F / "e1r_val_ahat_m.csv")
    rr_ = (am.a_hat / am.m).quantile([0.05, 0.25, 0.5, 0.75, 0.95])
    md += ["## E1-R validation tiles: a_hat / m per tile and band (data/p6_e1r/targets_val.h5 attributes)", "",
           f"- n = {len(am)} tile-bands; quantiles 5/25/50/75/95 %: " + ", ".join(f"{v:.4f}" for v in rr_), ""]
    gs = pd.read_csv(F / "gain_scales.csv")
    scales = ["bp_20_40", "bp_40_80", "bp_80_160", "lp_60"]
    med = gs.groupby(["domain", "ref", "scale"]).ratio.median().unstack("scale")[scales]
    md += ["## Gain at several scales (scripts/p6_gain_scales.py)", "", "Median ratio sd(B(D(ref)))/sd(B(x)):", "",
           med.round(3).to_markdown(), ""]
    sd = gs[gs.domain == "S"].copy()
    sd["rel"] = sd.ratio / sd.m_true
    md += ["Domain S, ratio / true gain (median):", "",
           sd.groupby(["ref", "scale"]).rel.median().unstack("scale")[scales].round(3).to_markdown(), ""]
    rr = gs[gs.domain == "R"].pivot_table(index=["tile", "band"], columns="scale", values="ratio")
    rel = rr.div(rr["lp_60"], axis=0)[scales]
    md += ["Domain R, per tile and band ratio / low-pass gain (quartiles):", "",
           rel.quantile([0.25, 0.5, 0.75]).round(3).to_markdown(), ""]
    brng = np.random.default_rng(2026)
    md += ["Median over tiles of the per-tile median ratio / low-pass gain, with 2,000 tile-bootstrap 95 % CI:", ""]
    for dom, tab in (("R", rel), ):
        for sc in scales[:3]:
            v = tab[sc].groupby(level=0).median().dropna()
            bs = [np.median(brng.choice(v.to_numpy(), len(v))) for _ in range(2000)]
            md.append(f"- domain R {sc}: {v.median():.3f} [{np.quantile(bs, 0.025):.3f}, {np.quantile(bs, 0.975):.3f}], "
                      f"n tiles {len(v)}")
    for sc in scales[:3]:
        v = sd[sd.scale == sc].groupby("tile").rel.median().dropna()
        bs = [np.median(brng.choice(v.to_numpy(), len(v))) for _ in range(2000)]
        md.append(f"- domain S {sc} (ratio / true gain): {v.median():.3f} [{np.quantile(bs, 0.025):.3f}, "
                  f"{np.quantile(bs, 0.975):.3f}], n tiles {len(v)}")
    md.append("")

    # E1-R per site and seed paired differences to the clean-target model (site means)
    import glob
    rows = []
    for f in glob.glob(str(ROOT / "runs/p6_e1r/S4_harmonized/*/seed*/eval.csv")):
        parts = Path(f).parts
        d = pd.read_csv(f).groupby(["site", "tile"])[["hp_corr", "hp_psnr", "edge_error"]].mean().groupby("site").mean()
        d["method"], d["seed"] = parts[-3], parts[-2]
        rows.append(d.reset_index())
    e = pd.concat(rows).pivot_table(index=["site", "seed"], columns="method", values=["hp_corr", "hp_psnr", "edge_error"])
    md += ["## E1-R paired differences to L1 on the true target, per site and seed (site means)", ""]
    for k in ("hp_corr", "hp_psnr", "edge_error"):
        for m in ("reg_l1_h", "reg_l1_inv", "reg_hp_h"):
            dd = (e[(k, m)] - e[(k, "reg_l1_clean")]).round(4).tolist()
            md.append(f"- {k}, {m}: {dd}")
    md.append("")
    md += ["Domain R, ratio / low-pass gain per band (median [IQR]):", ""]
    rb = rel.reset_index()
    for sc in scales[:3]:
        q = rb.groupby("band")[sc].quantile([0.25, 0.5, 0.75]).unstack()
        md.append(f"- {sc}: " + ", ".join(f"{b} {q.loc[b, 0.5]:.3f} [{q.loc[b, 0.25]:.3f}, {q.loc[b, 0.75]:.3f}]"
                                         for b in TARGET))
    md.append("")

    # sensitivity of E0 to the MTF (existing runs on a 454-tile subset)
    md += ["## E0 sensitivity to the MTF (results/p6_e0_mtf-0.05, results/p6_e0_mtf0.05; 454-tile subset)", ""]
    for d in ("p6_e0_mtf-0.05", "p6_e0_mtf0.05"):
        tt = pd.read_csv(ROOT / "results" / d / "tiles.csv")
        tt = tt[(tt.status == "ok") & (tt.g_peak >= 0.1)]
        bb = pd.read_csv(ROOT / "results" / d / "bands.csv")
        bb = bb[bb.band.isin(TARGET) & bb.tile.isin(tt.tile)]
        md.append(f"- {d}: n {len(tt)}, median target shift {tt.t_mag.median():.3f} px, median low-pass gain a_sd "
                  + ", ".join(f"{b} {v:.3f}" for b, v in bb.groupby('band').a_sd.median().reindex(TARGET).items()))
    md.append("")

    # attenuation of the high-pass detail by the cubic-spline shift used to register the reference
    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from scipy import ndimage as ndi
    from s2sr.p6.metrics import highpass
    from s2sr.registration import subpixel_shift
    img = ndi.gaussian_filter(np.random.default_rng(0).standard_normal((1, 256, 256)), (0, 1.0, 1.0))
    v = np.ones((256, 256), bool)
    h0 = highpass(img, v)[:, 40:-40, 40:-40].std()
    att = {sh: highpass(subpixel_shift(img, sh, sh), v)[:, 40:-40, 40:-40].std() / h0 for sh in (0.1, 0.25, 0.32, 0.5)}
    md += ["## High-pass attenuation by the cubic-spline shift (synthetic 10 m texture, shift in both axes)", "",
           "- " + ", ".join(f"shift {k} px: {v:.4f}" for k, v in att.items()), ""]
    (F / "facts.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
